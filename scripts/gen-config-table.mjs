const escapeCell = (value) => String(value ?? '').replace(/\|/g, '\\|');

/** 渲染指定语言的配置表（不含标记行）。 */
export function renderConfigTable(lang = 'zh') {
  if (lang !== 'zh' && lang !== 'en') throw new Error('lang must be zh|en');
  const lines = [TABLE_HEADERS[lang], '|---|---|---|'];
  for (const row of CONFIG_ROWS) {
    const value = typeof row.default === 'function' ? row.default(lang) : row.default;
    lines.push('| ' + row.key + ' | ' + escapeCell(value) + ' | ' + escapeCell(lang === 'zh' ? row.zh : row.en) + ' |');
  }
  return lines.join('\n');
}

/** 提取 README 标记区块内的表（失败抛错，不静默）。 */
export function extractConfigTable(readme) {
  const begin = readme.indexOf(CONFIG_TABLE_BEGIN);
  const end = readme.indexOf(CONFIG_TABLE_END, begin < 0 ? 0 : begin + CONFIG_TABLE_BEGIN.length);
  if (begin < 0 || end < 0) throw new Error('README 缺 config-table 标记（跑 node scripts/gen-config-table.mjs --write）');
  return readme.slice(begin + CONFIG_TABLE_BEGIN.length, end).trim();
}

/** 用生成表替换标记区块；标记不存在时按语言定位现有表并插入。 */
export function replaceConfigTable(readme, lang, table = renderConfigTable(lang)) {
  const block = CONFIG_TABLE_BEGIN + '\n' + table + '\n' + CONFIG_TABLE_END;
  const begin = readme.indexOf(CONFIG_TABLE_BEGIN);
  if (begin >= 0) {
    const end = readme.indexOf(CONFIG_TABLE_END, begin + CONFIG_TABLE_BEGIN.length);
    if (end < 0) throw new Error('README 有 config-table:begin 但缺 end');
    return readme.slice(0, begin) + block + readme.slice(end + CONFIG_TABLE_END.length);
  }
  const lines = readme.split('\n');
  const header = lines.indexOf(TABLE_HEADERS[lang]);
  if (header < 0) throw new Error('README 找不到配置表头：' + TABLE_HEADERS[lang]);
  let end = header;
  while (end < lines.length && lines[end].startsWith('|')) end += 1;
  return [...lines.slice(0, header), ...block.split('\n'), ...lines.slice(end)].join('\n');
}

/** 校验两份 README 的表与生成器一致；返回问题列表（空 = 通过）。 */
export function checkConfigTables() {
  const problems = [];
  for (const [lang, path] of Object.entries(README_FILES)) {
    let actual;
    try { actual = extractConfigTable(readFileSync(path, 'utf8')); } catch (error) { problems.push(path + ': ' + String(error?.message ?? error)); continue; }
    const expected = renderConfigTable(lang);
    if (actual !== expected) problems.push(path + ': 配置表与生成器不一致（跑 node scripts/gen-config-table.mjs --write）');
  }
  return problems;
}

/** 写回两份 README；返回实际改动的文件。 */
export function writeConfigTables() {
  const changed = [];
  for (const [lang, path] of Object.entries(README_FILES)) {
    const before = readFileSync(path, 'utf8');
    const after = replaceConfigTable(before, lang);
    if (after !== before) {
      writeFileSync(path, after);
      changed.push(path);
    }
  }
  return changed;
}

function main(argv) {
  if (argv.includes('--write')) {
    const changed = writeConfigTables();
    console.log(changed.length === 0 ? 'config table: 已是最新' : 'config table: 已写入 ' + changed.join(', '));
    return;
  }
  if (argv.includes('--check')) {
    const problems = checkConfigTables();
    if (problems.length > 0) {
      console.error(problems.join('\n'));
      process.exitCode = 1;
      return;
    }
    console.log('config table: OK');
    return;
  }
  const langIndex = argv.indexOf('--lang');
  const lang = langIndex >= 0 ? argv[langIndex + 1] : 'zh';
  console.log(renderConfigTable(lang));
}

const invoked = process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invoked) main(process.argv.slice(2));
