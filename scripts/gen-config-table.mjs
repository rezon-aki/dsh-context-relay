/** 从 lib/index.js 读取 AGENT_OPTION_KEYS（单一真源；不在此复制白名单）。 */
export function readAgentOptionKeys() {
  const match = /const AGENT_OPTION_KEYS = \[([\s\S]*?)\];/.exec(INDEX_SOURCE);
  if (match === null) throw new Error('lib/index.js 中找不到 AGENT_OPTION_KEYS');
  const keys = [...match[1].matchAll(/'([^']+)'/g)].map((item) => item[1]);
  if (keys.length === 0) throw new Error('AGENT_OPTION_KEYS 为空或格式变化');
  return keys;
}

